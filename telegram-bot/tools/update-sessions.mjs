#!/usr/bin/env node
// update-sessions.mjs — capture fresh Inception sessions on YOUR PC and embed
// them into the telegram bot's tgcloud/lib/sessions.js.
//
// This is the only step that runs on your machine (a few seconds, needs a
// browser). It reuses the bridge package's warmup.mjs (chromium solves the
// Vercel checkpoint automatically). Sessions expire after a few hours, so
// re-run this whenever the bot starts replying with checkpoint errors.
//
// Usage:
//   node tools/update-sessions.mjs            # runs warmup, then updates sessions.js
//   node tools/update-sessions.mjs --from /path/to/creds.json   # convert existing creds
//   node tools/update-sessions.mjs --count 3  # keep up to 3 sessions

import { spawn } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url))); // telegram-bot/
const BRIDGE_ROOT = path.dirname(ROOT);                                  // inception-portable/
const SESSIONS_FILE = path.join(ROOT, 'tgcloud', 'lib', 'sessions.js');

const args = process.argv.slice(2);
const arg = (name, dflt) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 && args[i + 1] ? args[i + 1] : dflt;
};
const COUNT = parseInt(arg('count', '3'), 10);
const FROM = arg('from', '');

async function obtainSessions() {
  if (FROM) {
    const raw = fs.readFileSync(FROM, 'utf8');
    const d = JSON.parse(raw);
    const arr = Array.isArray(d) ? d : d.active || [];
    return arr.filter(a => a && a.bearer);
  }
  const tmp = path.join(os.tmpdir(), `creds-${Date.now()}.json`);
  const warmup = path.join(BRIDGE_ROOT, 'warmup.mjs');
  await new Promise((resolve, reject) => {
    const child = spawn(process.execPath, [warmup, '--output', tmp, '--headless', '--timeout-ms', '150000'], {
      stdio: ['ignore', 'pipe', 'pipe'],
    });
    let out = '';
    child.stdout.on('data', d => (out += d));
    child.stderr.on('data', d => (out += d));
    child.on('close', code => {
      console.log('[warmup]', out.trim().split('\n').slice(-3).join(' | '));
      if (code !== 0) return reject(new Error(`warmup failed (exit ${code})`));
      resolve();
    });
    child.on('error', reject);
  });
  const d = JSON.parse(fs.readFileSync(tmp, 'utf8'));
  fs.rmSync(tmp, { force: true });
  return (Array.isArray(d) ? d : d.active || []).filter(a => a && a.bearer);
}

function render(sessions) {
  const lines = [
    '// Sessions for direct mode — AUTO-GENERATED by tools/update-sessions.mjs',
    '// (do not edit by hand; re-run the tool to refresh).',
    '',
    `export const sessions = ${JSON.stringify(sessions, null, 2)};`,
    '',
  ];
  return lines.join('\n');
}

const sessions = (await obtainSessions()).slice(0, COUNT);
if (!sessions.length) {
  console.error('no sessions obtained — nothing written');
  process.exit(1);
}
fs.writeFileSync(SESSIONS_FILE, render(sessions));
console.log(`wrote ${sessions.length} session(s) -> ${path.relative(ROOT, SESSIONS_FILE)}`);
console.log('\nnext: npx tgcloud push   (redeploy the bot)');
